def srcs(*lst):
    return "<p>" + B.srcs(list(lst)) + "</p>"


def table(head, rows):
    h = "".join(f"<th>{c}</th>" for c in head)
    # ひな形の表は2列目から折り返さない。長い文の列だけ折り返す(スマホで横に長くなりすぎないように)
    mw = "min-width:13em" if len(head) >= 3 else "min-width:8em"
    def td(c):
        return f'<td style="white-space:normal;{mw}">{c}</td>' if len(K.strip_tags(c)) > 14 else f"<td>{c}</td>"
    b = "".join("<tr>" + "".join(td(c) for c in r) + "</tr>" for r in rows)
    return f"<table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table>"


def faq_html(faq):
    return '<h2 id="faq">よくある質問</h2>\n' + "\n".join(f"<h3>{e(q)}</h3>\n<p>{a}</p>" for q, a in faq)


