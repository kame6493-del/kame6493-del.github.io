def box(key, ct):
    html = K.nigatecho_box(key)
    ios = B.store_urls(key)[0]
    ct_url = f"{ios}{'&' if '?' in ios else '?'}pt={PT_TOKEN}&ct={ct}&mt=8"
    html = html.replace(f'href="{ios}"', f'href="{ct_url}"')
    src, alt = SHOTS.get(ct.replace("web_", ""), SHOTS.get(key))
    w, h = K._img_size(src)
    html = re.sub(r'<div class="app-shot">.*?</div>',
                  f'<div class="app-shot"><img src="{src}" alt="{e(alt)}" width="{w}" height="{h}" loading="lazy" decoding="async"></div>',
                  html, count=1, flags=re.S)
    if key in FEAT:
        html = html.replace("間違えた問題は「苦手」として残り、2回続けて正解すると消えます。", FEAT[key], 1)
    return html


