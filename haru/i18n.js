const EN_CACHE = new Map();
const EN_MISS = new Set();
function enOf(s) {
  if (Object.prototype.hasOwnProperty.call(EN_DICT, s)) return EN_DICT[s];
  const tr = s.trim();
  if (tr !== s && Object.prototype.hasOwnProperty.call(EN_DICT, tr)) return EN_DICT[tr];
  for (const [re, fn] of EN_PAT) { const m = re.exec(s); if (m) return fn(m); }
  // 2つ以上の 空白で 区切った 文は 1つずつ
  const parts = s.split(/( {2,})/);
  if (parts.length > 1) return parts.map(p => /^ +$/.test(p) ? p : T(p)).join('');
  if (s.includes('・')) return enList(s);
  EN_MISS.add(s);
  return s;
}
// 日本語の 文を いまの ことばに する(日本語の ときは そのまま)
function T(s) {
  if (LANG !== 'en' || typeof s !== 'string' || !JP_RE.test(s)) return s;
  let v = EN_CACHE.get(s);
  if (v === undefined) { v = enOf(s); EN_CACHE.set(s, v); }
  return v;
}
// 英語の 文を 横はばで 折りかえす(ことばの 切れ目で)
function wrapWords(c, text, maxW) {
  const out = []; let line = '';
  for (const w of String(text).split(/ +/)) {
    const s2 = line ? line + ' ' + w : w;
    if (line && c.measureText(s2).width > maxW) { out.push(line); line = w; } else line = s2;
  }
  if (line) out.push(line);
  return out;
}
