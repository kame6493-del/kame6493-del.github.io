const LANG_KEY = 'haru_lang';
let LANG = (function () {
  try { const m = /[?&]lang=(en|ja)\b/.exec(location.search || ''); if (m) return m[1]; } catch (e) { /* 無視 */ }
  try { const s = localStorage.getItem(LANG_KEY); if (s === 'en' || s === 'ja') return s; } catch (e) { /* 保存が つかえない */ }
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'ja';
  return /^ja\b/i.test(nav) ? 'ja' : 'en';
})();
const isEN = () => LANG === 'en';
function applyLangDoc() {
  try {
    document.documentElement.lang = LANG;
    document.title = isEN() ? "Haru's Adventure" : 'ハルの冒険';
    const c = document.getElementById('c'); if (c) c.setAttribute('aria-label', isEN() ? "Haru's Adventure game screen" : 'ハルの冒険 ゲーム画面');
  } catch (e) { /* 無視 */ }
}
function setLang(l) {
  if (l !== 'en' && l !== 'ja') return;
  LANG = l;
  try { localStorage.setItem(LANG_KEY, l); } catch (e) { /* 保存が つかえなくても きりかえは できる */ }
  applyLangDoc();
}
