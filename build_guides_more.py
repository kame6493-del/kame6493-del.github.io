def add_sitemap(fname, base, paths, mods=None):
    p = os.path.join(ROOT, fname)
    s = open(p, encoding="utf-8").read()
    mods = mods or {}
    for path in paths:
        u = base + path
        day = mods.get(path, DAY)
        if f"<loc>{u}</loc>" not in s:
            s = s.replace("</urlset>", f"<url><loc>{u}</loc><lastmod>{day}</lastmod></url>\n</urlset>")
        else:
            s = re.sub(r"(<loc>" + re.escape(u) + r"</loc>\s*<lastmod>)[^<]*(</lastmod>)", lambda m: m.group(1) + day + m.group(2), s)
    open(p, "w", encoding="utf-8", newline="\n").write(s)


