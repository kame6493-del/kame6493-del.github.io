def countdown(items):
    """items: [(何まで, 日付の表示, ISO の日付, 過ぎたときの文)]"""
    lis = "".join(f'<li data-cd="{iso}" data-after="{e(after)}"><span>{e(what)}</span><b>{e(ja)}</b><em></em></li>'
                  for what, ja, iso, after in items)
    return f'{CD_CSS}<ul class="cd" aria-live="polite">{lis}</ul>{CD_JS}'


